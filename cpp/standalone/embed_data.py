#!/usr/bin/env python3
"""Embed src/data/*.json into embedded_data.hpp so the terminal game runs without any files."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
data = root / 'src' / 'data'

def literal(text: str) -> str:
    # Raw string literals, chunked to stay under MSVC's per-literal limit.
    parts = [text[i:i + 8000] for i in range(0, len(text), 8000)] or ['']
    return '\n'.join(f'R"CAUJSON({p})CAUJSON"' for p in parts)

def compact(path: pathlib.Path) -> str:
    return json.dumps(json.loads(path.read_text(encoding='utf-8')), ensure_ascii=False, separators=(',', ':'))

rooms = '[' + ','.join(compact(p) for p in sorted((data / 'rooms').glob('*.json'))) + ']'
texts = {p.stem: compact(p) for p in sorted((data / 'text').glob('*.json'))}

out = ['// Generated by cpp/standalone/embed_data.py from src/data/. Do not edit by hand.',
       '#pragma once', '#include <string>', '', 'namespace embedded {', '']
for name, path in [('enemies', 'enemies.json'), ('courses', 'courses.json'), ('professors', 'professors.json'), ('campus', 'campus.json')]:
    out.append(f'inline std::string {name}() {{\n  return {literal(compact(data / path))};\n}}\n')
out.append(f'inline std::string rooms() {{\n  return {literal(rooms)};\n}}\n')
out.append('inline std::string text(const std::string& lang) {')
for lang, body in texts.items():
    out.append(f'  if (lang == "{lang}") return {literal(body)};')
out.append('  return "";\n}\n')
out.append('}  // namespace embedded\n')
(pathlib.Path(__file__).parent / 'embedded_data.hpp').write_text('\n'.join(out), encoding='utf-8')
print('wrote embedded_data.hpp')
