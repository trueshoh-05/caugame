#!/usr/bin/env python3
"""Merge the C++ core, the embedded data and the terminal front end into ONE .cpp file:
cau_semester_survivor.cpp, which compiles on its own with any C++17 compiler."""
import pathlib, re, subprocess, sys

here = pathlib.Path(__file__).resolve().parent
src = here.parent / 'src'
subprocess.run([sys.executable, str(here / 'embed_data.py')], check=True)

order = [src / 'json.hpp', src / 'rng.hpp', src / 'data.hpp', src / 'rules.hpp', src / 'campus.hpp', src / 'arena.hpp',
         here / 'embedded_data.hpp',
         src / 'json.cpp', src / 'data.cpp', src / 'rules.cpp', src / 'campus.cpp', src / 'arena.cpp',
         here / 'main.cpp']
system_includes, body = [], []
for f in order:
    text = f.read_text(encoding='utf-8')
    lines = []
    for line in text.splitlines():
        if line.strip() == '#pragma once' or re.match(r'\s*#include\s+"', line):
            continue
        m = re.match(r'\s*#include\s+<([^>]+)>', line)
        if m and not line.lstrip().startswith('#include <conio') and not line.lstrip().startswith('#include <windows') \
                and not line.lstrip().startswith('#include <sys/') and not line.lstrip().startswith('#include <termios') \
                and not line.lstrip().startswith('#include <unistd'):
            if m.group(1) not in system_includes:
                system_includes.append(m.group(1))
            continue
        lines.append(line)
    body.append(f'// ===== {f.relative_to(here.parent)} =====\n' + '\n'.join(lines))

header = """// CAU: Semester Survivor — terminal edition, in one file.
// Generated by cpp/standalone/make_single_file.py from the game's C++ core (cpp/src) and data (src/data).
//
// Build and play (any C++17 compiler, no libraries):
//   macOS:   clang++ -std=c++17 -O2 cau_semester_survivor.cpp -o cau && ./cau
//   Linux:   g++ -std=c++17 -O2 cau_semester_survivor.cpp -o cau && ./cau
//   Windows: cl /std:c++17 /O2 /EHsc /utf-8 cau_semester_survivor.cpp && cau.exe
"""
out = header + '\n' + '\n'.join(f'#include <{h}>' for h in system_includes) + '\n\n' + '\n\n'.join(body) + '\n'
(here / 'cau_semester_survivor.cpp').write_text(out, encoding='utf-8')
print(f'wrote cau_semester_survivor.cpp ({len(out) // 1024} KB, {out.count(chr(10))} lines)')
